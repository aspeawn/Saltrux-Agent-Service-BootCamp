package lecture.section02.looping;

public class C_doWhile {

    public void sampleDoWhile() {
        /*
        * Do While문 표현방법
        *
        * 초기식;
        * do {
        *   반복시키고 싶은 코드
        *   증감식
        * } while (조건식);
        * */
        do {
            System.out.println("최초 한 번 동작");
        } while (false);
        System.out.println("반복문 종료됨...");
    }


}
